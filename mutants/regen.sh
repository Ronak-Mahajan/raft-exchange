#!/usr/bin/env bash
# mutants/regen.sh - regenerate every mutants/*.patch from the current src/.
#
# Each mutant is one exact, literal substitution against src/raft.hpp or
# src/exchange.hpp. This script applies the substitution to a scratch copy,
# diffs it against the original, and writes the unified diff (with the
# header block that names the rule, the break, and the expected killer) to
# mutants/<name>.patch. Run it after any edit to src/ that makes run.sh
# report APPLY-FAILED; the substitutions are the source of truth, the
# patches are the artifact the gate consumes.
#
# A substitution that matches nothing is an error: a mutant that silently
# stops mutating would be a green gate with no teeth.
#
# Usage: bash mutants/regen.sh
set -eu

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/mutants"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

count=0

# emit NAME FILE PERL-SUBSTITUTION HEADER
emit() {
    local name="$1" file="$2" expr="$3" header="$4"
    local dir="$WORK/$name"
    mkdir -p "$dir/a/$(dirname "$file")" "$dir/b/$(dirname "$file")"
    # Normalise to LF so the patch is identical on every checkout.
    tr -d '\r' < "$ROOT/$file" > "$dir/a/$file"
    cp "$dir/a/$file" "$dir/b/$file"
    perl -0pi -e "$expr" "$dir/b/$file"
    if cmp -s "$dir/a/$file" "$dir/b/$file"; then
        echo "regen: $name: substitution matched nothing in $file" >&2
        exit 1
    fi
    {
        printf '%s\n' "$header"
        echo "#"
        echo "# Generated by mutants/regen.sh; edit the substitution there, not this file."
        (cd "$dir" && diff -u --label "a/$file" --label "b/$file" "a/$file" "b/$file") || true
    } > "$OUT/$name.patch"
    count=$((count + 1))
    echo "wrote mutants/$name.patch"
}

